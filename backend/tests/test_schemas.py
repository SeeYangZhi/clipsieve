@pytest.mark.parametrize("n", [1, 2, 3, 4, 5])
def test_fixture_posts_validate_and_keep_cjk(fixtures_dir: Path, n: int):
    from clipsieve.models import Post

    raw = (fixtures_dir / "posts" / f"local__fx-00{n}.json").read_text(encoding="utf-8")
    post = Post.model_validate_json(raw)
    assert post.id == f"local:fx-00{n}"
    assert (fixtures_dir / post.raw_ref).exists()
    assert len(post.comments) <= 50
    dumped = json.loads(post.model_dump_json())
    assert dumped["text"]["title"] == json.loads(raw)["text"]["title"]


def test_cjk_fixture_roundtrip_is_bytewise(fixtures_dir: Path):
    from clipsieve.models import Post

    post = Post.model_validate_json(
        (fixtures_dir / "posts/local__fx-003.json").read_text(encoding="utf-8")
    )
    assert post.text.title == "上海超市物价大公开 🇸🇬→🇨🇳"
    assert post.comments[0].text == "第4张真的绝了"
    assert post.kind.value == "image_note"
    assert len(post.media) == 4
