from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "packages" / "schema"))

from merge import merge  # noqa: E402

SCHEMA_FILES = [
    "common.json",
    "post.json",
    "evidence.json",
    "run_event.json",
    "rubric_pack.json",
    "plan.json",
    "report.json",
    "judge_result.json",
    "run.json",
]


def test_every_schema_file_present_and_titled():
    for name in SCHEMA_FILES:
        doc = json.loads((ROOT / "packages/schema/schemas" / name).read_text(encoding="utf-8"))
        assert doc["title"], name
        assert doc["$id"] == f"https://clipsieve.dev/schema/{name}"


def test_merge_flattens_refs_and_has_no_file_refs():
    merged = merge()
    text = json.dumps(merged)
    assert ".json#/" not in text
    for name in [
        "Post",
        "Evidence",
        "RunEvent",
        "RubricPack",
        "Plan",
        "Report",
        "JudgeResult",
        "Run",
        "Brief",
        "Counters",
        "Stage",
    ]:
        assert name in merged["$defs"], name


